import {readFileSync,writeFileSync,mkdirSync,copyFileSync,existsSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
// Default saves the signed website apps; --usb saves the debug development apps.
const usb=process.argv.includes('--usb');
const root=fileURLToPath(new URL('../',import.meta.url)),out=new URL('./releases/',import.meta.url);
mkdirSync(out,{recursive:true});
const gradle=readFileSync(new URL('./android/app/build.gradle',import.meta.url),'utf8');
const versionCode=Number(gradle.match(/versionCode (\d+)/)[1]),base=gradle.match(/versionName '([^']+)'/)[1],versionName=usb?base+'-usb':base;
const git=(...a)=>execFileSync('git',a,{cwd:root,encoding:'utf8',windowsHide:true}).trim();
const dirty=Boolean(git('status','--porcelain','--','.'));
const apps=[];
for(const flavor of ['driver','booking']){
 const source=new URL(`./android/app/build/outputs/apk/${flavor}/${usb?'debug':'release'}/app-${flavor}-${usb?'debug':'release'}.apk`,import.meta.url);
 if(!existsSync(source))throw Error('Missing signed APK for '+flavor+'. Run npm.cmd run '+(usb?'mobile:build:usb':'mobile:build')+' first.');
 const bytes=readFileSync(source);
 if(bytes.length<1000||bytes.readUInt32LE(0)!==0x04034b50)throw Error('Invalid built APK.');
 const filename=`Safeer-${flavor==='driver'?'Driver':'Booking'}-${versionName}.apk`,sha256=createHash('sha256').update(bytes).digest('hex');
 copyFileSync(source,new URL(filename,out));writeFileSync(new URL(filename+'.sha256',out),`${sha256}  ${filename}\n`);
 apps.push({applicationId:'sd.safeer.'+flavor,versionName,versionCode,filename,bytes:bytes.length,sha256});
}
writeFileSync(new URL('latest.json',out),JSON.stringify({channel:usb?'debug-usb-local':'website',builtAt:new Date().toISOString(),sourceCommit:dirty?null:git('rev-parse','HEAD'),packagingCommit:git('rev-parse','HEAD'),sourceDirty:dirty,serverOrigin:usb?'http://127.0.0.1:4320':'https://safeer.mohbaba.online',requiresRunningComputerAndUsbTunnel:usb,apps},null,2)+'\n');
// D60: the website's Download/Update buttons read src/app-release.js. The APKs
// themselves are attached to the GitHub release tag, never committed.
if(!usb){
 const tag='v'+versionName,download='https://github.com/Baballah2240/Safeer/releases/download/'+tag+'/';
 const info={versionName,versionCode,tag,releasePage:'https://github.com/Baballah2240/Safeer/releases/tag/'+tag,apps:Object.fromEntries(apps.map(a=>[a.applicationId.split('.').pop(),{url:download+a.filename,sha256:a.sha256,bytes:a.bytes}]))};
 const body=['// Generated by npm run mobile:save (D60). Latest signed Android apps on GitHub releases.','export const appRelease='+JSON.stringify(info,null,1)+';',''].join('\r\n');
 writeFileSync(new URL('../src/app-release.js',import.meta.url),body);
}
console.log(`Saved both Safeer ${usb?'USB development':'website'} APKs, SHA-256 sidecars and mobile/releases/latest.json${usb?'':' and src/app-release.js'}.`);
